  mkdirSync(resolve(__dirname, 'dist'), { recursive: true });
  writeFileSync(resolve(__dirname, 'dist/host-bundle.js'), buildHostBundle(), 'utf8');
  writeFileSync(resolve(__dirname, 'dist/client-bundle.js'), buildClientBundle(), 'utf8');
