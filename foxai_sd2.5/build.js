// 简化函数：去除注释
function minify(src) {
  return src
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/^(\s*)\/\/.*$/gm, '')
    .replace(/\n{3,}/g, '\n\n');
}

// 加载源文件，自动 minify 到 src/min/（如果还没 minify 的话）
function loadOrMinify(srcPath, minPath) {
  const src = readFileSync(resolve(__dirname, srcPath), 'utf8');
  if (!existsSync(resolve(__dirname, minPath))) {
    writeFileSync(resolve(__dirname, minPath), minify(src), 'utf8');
  }
  return readFileSync(resolve(__dirname, minPath), 'utf8');
}

// 把 ES Module 转成可被脚本上下文中执行的闭包
// 策略：
//   1. 收集所有 `export const NAME` 和 `export function NAME` 的 NAME
//   2. 把 `export` 关键字去掉
//   3. 在 IIFE 末尾返回 { NAME1, NAME2, ... } 这个聚合对象
//   4. 如果文件中有显式的 `export const MODULE_NAME = ...` 则返回它（向后兼容）
function moduleToCjs(name, source) {
  // 1. 移除 import 语句
  let cleaned = source.replace(/^import\s+.*?from\s+['"][^'"]+['"];?$/gm, '');

  // 2. 收集所有导出的名字
  const exportedNames = [];
  cleaned = cleaned.replace(/^export\s+const\s+(\w+)/gm, (_, n) => {
    exportedNames.push(n);
    return 'const ' + n;
  });
  cleaned = cleaned.replace(/^export\s+async\s+function\s+(\w+)/gm, (_, n) => {
    exportedNames.push(n);
    return 'async function ' + n;
  });
  cleaned = cleaned.replace(/^export\s+function\s+(\w+)/gm, (_, n) => {
    exportedNames.push(n);
    return 'function ' + n;
  });
  cleaned = cleaned.replace(/^export\s+class\s+(\w+)/gm, (_, n) => {
    exportedNames.push(n);
    return 'class ' + n;
  });

  // 3. 如果文件中有显式的顶层 const <name> = ... ，优先返回它
  const hasAggregate = new RegExp('^const\\s+' + name + '\\s*=', 'm').test(cleaned);

  let returnExpr;
  if (hasAggregate) {
    returnExpr = 'return ' + name + ';';
  } else {
    // 否则返回所有导出的聚合
    returnExpr = 'return { ' + exportedNames.join(', ') + ' };';
  }

  // 4. 处理剩余的 export default / export { ... }（简单兜底）
  cleaned = cleaned.replace(/^export\s+default\s+/gm, '');
  cleaned = cleaned.replace(/^export\s*\{\s*([^}]+)\s*\};?$/gm, '');

  return 'const ' + name + ' = (() => {\n' + cleaned + '\n' + returnExpr + '\n})();\n';
}

